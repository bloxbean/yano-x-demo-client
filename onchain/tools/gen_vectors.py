"""Fetch a real orders-chain message, its envelope and its state proof at the anchored height from the
public showcase, and emit an Aiken test module (onchain/lib/vectors/orders.ak) using those exact bytes."""
import base64, json, pathlib, sys, urllib.request, hashlib
import cbor2, ssl

CTX = ssl.create_default_context(cafile="/etc/ssl/cert.pem")

NODE = "https://node0-showcase.yano-x.io/api/v1/app-chain/chains"
get = lambda u: json.load(urllib.request.urlopen(urllib.request.Request(u, headers={"User-Agent": "anchor-proofs"}), timeout=30, context=CTX))
b64 = lambda s: base64.b64decode(s).hex()

def step(t):
    tag, f = t.tag, t.value
    if tag == 121:
        return f"Branch {{ skip: {f[0]}, neighbors: #\"{f[1].hex()}\" }}"
    if tag == 122:
        n = f[1].value
        return f"Fork {{ skip: {f[0]}, neighbor: Neighbor {{ nibble: {n[0]}, prefix: #\"{n[1].hex()}\", root: #\"{n[2].hex()}\" }} }}"
    if tag == 123:
        return f"Leaf {{ skip: {f[0]}, key: #\"{f[1].hex()}\", value: #\"{f[2].hex()}\" }}"
    raise SystemExit(f"unexpected proof step tag {tag}")

def main():
    chain = "orders-chain"
    anchor = get(f"{NODE}/{chain}/anchor/commitment")
    height = anchor["anchoredHeight"]
    blk = get(f"{NODE}/{chain}/blocks/{height}")
    mid = blk["messages"][0]["messageId"]
    pkg = get(f"{NODE}/{chain}/messages/{mid}/proof-package")["suppliedMessage"]
    key = hashlib.sha256(b"~yano/finalized-message/v1/" + bytes.fromhex(mid)).hexdigest()
    sp = get(f"{NODE}/{chain}/state/proof/{key}?height={height}")
    assert sp["stateRoot"] == anchor["stateRoot"] and sp["presence"] == "PRESENT"
    steps = cbor2.loads(bytes.fromhex(sp["proofWireHex"]))
    out = f"""//// Generated by tools/gen_vectors.py from the public showcase. Real bytes; do not edit.
use aiken/merkle_patricia_forestry.{{Branch, Fork, Leaf, Neighbor, Proof}}

pub const chain_id = "{chain}"
pub const anchored_height = {height}
pub const state_root = #"{anchor['stateRoot']}"
pub const message_id = #"{mid}"
pub const topic = "{pkg['topic']}"
pub const sender = #"{b64(pkg['sender'])}"
pub const sender_seq = {pkg['senderSeq']}
pub const expires_at = {pkg['expiresAt']}
pub const body = #"{b64(pkg['body'])}"
pub const block_height = {sp['committedHeight'] if False else blk['height']}
pub const message_index = 0
pub const state_key = #"{key}"
pub const state_value = #"{sp['valueHex']}"

pub fn proof() -> Proof {{
  [
    {(',' + chr(10) + '    ').join(step(s) for s in steps)},
  ]
}}
"""
    path = pathlib.Path(__file__).resolve().parents[1] / "lib/vectors/orders.ak"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(out)
    print("wrote", path, "height", height, "steps", len(steps), "body", bytes.fromhex(b64(pkg['body'])).decode())

main()
