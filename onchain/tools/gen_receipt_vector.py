"""Emit onchain/lib/vectors/receipt.ak: a real document-review release receipt and its proof at the anchored height."""
import json, pathlib, ssl, sys, urllib.request
import cbor2
CTX = ssl.create_default_context(cafile="/etc/ssl/cert.pem")
NODE = "https://node0-showcase.yano-x.io/api/v1/app-chain/chains/document-review-chain"
get = lambda u: json.load(urllib.request.urlopen(urllib.request.Request(u, headers={"User-Agent": "anchor-proofs"}), timeout=30, context=CTX))
proposal = sys.argv[1]
cid, local = b"document-review-receipts", b"approval/" + proposal.encode()
key = b"yano-composite-state-v1\0" + bytes([len(cid)]) + cid + len(local).to_bytes(2, "big") + local
anchor = get(f"{NODE}/anchor/commitment")
sp = get(f"{NODE}/state/proof/{key.hex()}?height={anchor['anchoredHeight']}")
assert sp["presence"] == "PRESENT" and sp["stateRoot"] == anchor["stateRoot"]
v = cbor2.loads(bytes.fromhex(sp["valueHex"]))
def step(t):
    f = t.value
    if t.tag == 121: return f'Branch {{ skip: {f[0]}, neighbors: #"{f[1].hex()}" }}'
    if t.tag == 122:
        n = f[1].value; return f'Fork {{ skip: {f[0]}, neighbor: Neighbor {{ nibble: {n[0]}, prefix: #"{n[1].hex()}", root: #"{n[2].hex()}" }} }}'
    return f'Leaf {{ skip: {f[0]}, key: #"{f[1].hex()}", value: #"{f[2].hex()}" }}'
steps = cbor2.loads(bytes.fromhex(sp["proofWireHex"]))
used = sorted({s.split(' ')[0] for s in map(step, steps)})
out = f'''//// Generated by tools/gen_receipt_vector.py from the public showcase. Real bytes; do not edit.
use aiken/merkle_patricia_forestry.{{{", ".join(used + (["Neighbor"] if "Fork" in used else []) + ["Proof"])}}}
use yano/records.{{ReleaseReceipt}}

pub const anchored_height = {anchor['anchoredHeight']}
pub const state_root = #"{anchor['stateRoot']}"
pub const state_key = #"{key.hex()}"
pub const state_value = #"{sp['valueHex']}"

pub fn receipt() -> ReleaseReceipt {{
  ReleaseReceipt {{
    proposal_id: "{v[1]}",
    entity_id: "{v[2]}",
    action_commitment: #"{v[3].hex()}",
    policy_id: "{v[4]}",
    policy_revision: {v[5]},
    applied_height: {v[6]},
    message_id: #"{v[7].hex()}",
  }}
}}

pub fn proof() -> Proof {{
  [
    {(","+chr(10)+"    ").join(map(step, steps))},
  ]
}}
'''
(pathlib.Path(__file__).resolve().parents[1] / "lib/vectors/receipt.ak").write_text(out)
print("height", anchor["anchoredHeight"], "steps", len(steps), "value", v)
